"""
Job context store for Stage 1 (temporary in-memory implementation).

The registry remembers the small amount of state the API needs between two
separate HTTP requests: the request that creates the upload, and the later
request that validates it. Without it, the validate endpoint would not know
which S3 key belongs to a `job_id` — and letting the client supply the key would
let it point at arbitrary objects.

Position in the architecture:
    intake service -> JobRegistry (state)  ... alongside S3/SQS adapters

What it stores: job metadata and state only (job id, original filename,
server-generated S3 key, status, handoff marker). Dataset bytes live in S3.

Known technical debt — `InMemoryJobRegistry` is intentionally temporary:
- it is process-local, so a second API instance cannot see these jobs
- all state is lost on restart or redeploy
- it therefore cannot support horizontal scaling or shared worker access
A persistent shared store replaces it in a later milestone; the `JobRegistry`
Protocol exists so that swap does not touch service code.
"""

from __future__ import annotations

import threading
from dataclasses import dataclass
from typing import Protocol

from app.intake.schemas import JobStatus


@dataclass
class IntakeJobRecord:
    """
    Server-side context for one intake job.

    `s3_key` is generated by the service and stored here so the validate
    endpoint can resolve a `job_id` to an object without trusting client input.

    The two handoff fields record that the SQS publish for this job already
    happened, which is what makes a repeated validate call skip publishing.
    They are in-process state only, not a durable idempotency guarantee (see the
    module docstring of `app/intake/service.py`).
    """

    job_id: str
    filename: str
    s3_key: str
    status: JobStatus = JobStatus.RECEIVED
    # Process-local SQS handoff marker (M3). Not durable across process restarts.
    message_published: bool = False
    published_message_id: str | None = None


class JobRegistry(Protocol):
    """
    Interface the intake service depends on.

    A Protocol (structural typing) rather than a base class: the service is
    written against these four operations, so a persistent implementation can be
    introduced later without inheriting from anything here, and tests can supply
    a simple stand-in.
    """

    def put(self, record: IntakeJobRecord) -> None: ...

    def get(self, job_id: str) -> IntakeJobRecord | None: ...

    def update_status(self, job_id: str, status: JobStatus) -> None: ...

    def mark_published(self, job_id: str, published_message_id: str) -> None: ...


class InMemoryJobRegistry:
    """
    Process-local registry for M2/M3 (no Redis/database).

    A plain dict guarded by a lock. The lock matters because FastAPI serves
    sync endpoints from a thread pool, so several requests can touch the dict
    concurrently within this one process.

    Mutating methods are no-ops for unknown job ids: the service has already
    established the job exists (and reports `JOB_NOT_FOUND` when it does not),
    so this layer does not raise on a missing key.
    """

    def __init__(self) -> None:
        self._jobs: dict[str, IntakeJobRecord] = {}
        self._lock = threading.Lock()

    def put(self, record: IntakeJobRecord) -> None:
        """Store a newly created job record (first write of the RECEIVED state)."""
        with self._lock:
            self._jobs[record.job_id] = record

    def get(self, job_id: str) -> IntakeJobRecord | None:
        """
        Look up a job, or return None when this process has never seen it.

        Returns the live record object, so callers observe later mutations; the
        service relies on reading the current `message_published` value.
        """
        with self._lock:
            return self._jobs.get(job_id)

    def update_status(self, job_id: str, status: JobStatus) -> None:
        """Record a state transition (RECEIVED -> VALIDATING -> VALIDATED | REJECTED)."""
        with self._lock:
            record = self._jobs.get(job_id)
            if record is not None:
                record.status = status

    def mark_published(self, job_id: str, published_message_id: str) -> None:
        """
        Record that the PROCESS_DATASET command for this job was accepted by SQS.

        Called by the service only after a successful SendMessage, so a failed
        publish leaves the job publishable and a repeated validate does not
        enqueue the same work twice within this process.
        """
        with self._lock:
            record = self._jobs.get(job_id)
            if record is not None:
                record.message_published = True
                record.published_message_id = published_message_id

    def clear(self) -> None:
        """Drop all state. Used by tests to isolate the module-level instance."""
        with self._lock:
            self._jobs.clear()


# Module-level instance: the registry must outlive individual requests, so it
# cannot be created per request. Its lifetime is the lifetime of this process,
# which is exactly the limitation described in the module docstring.
_registry = InMemoryJobRegistry()


def get_job_registry() -> InMemoryJobRegistry:
    """
    FastAPI dependency provider for the shared registry.

    Routers depend on this function rather than importing `_registry` directly,
    so tests can override it via `app.dependency_overrides` and a future
    persistent implementation can be wired in from one place.
    """
    return _registry
