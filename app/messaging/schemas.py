"""
Message contract for the Stage 1 -> worker handoff.

This module defines the versioned envelope that crosses the SQS boundary. It is
the shared contract between two independently deployed processes:

    API process  (publisher) -> SQS -> worker process (consumer)

Because publisher and consumer are deployed separately, they can run different
code versions at the same time. The envelope therefore carries its own explicit
type and version instead of relying on both sides being upgraded together, and
the consumer validates every message before acting on it.

Three different identifiers appear around one message; keeping them distinct
matters when reading logs:

- `job_id`        business identity of the intake job. Created by the intake
                  service, returned to the client, and reused for every message
                  and log line about that job.
- `message_id`    identity of this specific command/message, generated by the
                  publisher (see `build_process_dataset_message`).
- AWS `MessageId` identifier SQS itself assigns when it accepts the message. It
                  is not part of the envelope; it is returned by SendMessage and
                  reported again on receive (`ReceivedMessage.message_id`).

Serialization/transport (boto3, queue URL) belongs to `app/infrastructure/sqs.py`,
and the decision to publish belongs to `app/intake/service.py`. This module only
describes the data.
"""

from __future__ import annotations

from datetime import UTC, datetime
from enum import Enum
from typing import Literal
from uuid import uuid4

from pydantic import BaseModel, Field, field_validator


class MessageType(str, Enum):
    """
    Command types the job queue accepts.

    An enum rather than a free-form string, so an unknown type fails envelope
    validation on the consumer instead of being silently processed as if it were
    understood. New asynchronous operations are added here as new members.
    """

    PROCESS_DATASET = "PROCESS_DATASET"


class ProcessDatasetPayload(BaseModel):
    """
    Payload of `PROCESS_DATASET`: where the validated dataset lives.

    The payload carries an S3 pointer (bucket + key) rather than dataset bytes:
    SQS has a per-message size limit and S3 is already the durable store. A real
    Stage 2 processor can use this pointer to read the object from S3. The
    current M3 simulated processor does not read the object.
    """

    s3_bucket: str = Field(min_length=1, description="S3 bucket holding the validated object.")
    s3_key: str = Field(min_length=1, description="S3 object key for the validated CSV.")


class JobCommandMessage(BaseModel):
    """
    The versioned envelope placed on the job queue.

    `PROCESS_DATASET` is a command: it tells the worker which work is requested
    for which job, rather than merely announcing that something happened.

    The consumer validates an incoming body against this model before any
    processing, so a malformed or unknown-shaped message is rejected at the
    boundary (see `WorkerService.handle_received_message`).
    """

    message_id: str = Field(description="Unique id for this queue message (publisher-generated).")
    message_type: MessageType
    # A literal (not a plain int) makes the supported version part of the type:
    # a future schema_version=2 message fails validation here instead of being
    # misinterpreted by a consumer that only understands version 1.
    schema_version: Literal[1] = Field(description="Envelope schema version.")
    created_at: datetime = Field(description="UTC timestamp when the message was created.")
    job_id: str = Field(min_length=1, description="Intake job id this command belongs to.")
    payload: ProcessDatasetPayload

    @field_validator("created_at")
    @classmethod
    def _require_utc(cls, value: datetime) -> datetime:
        # Timestamps cross process, host, and possibly region boundaries, so a
        # naive datetime is ambiguous and rejected. Aware values are normalized
        # to UTC to keep comparisons and logs consistent.
        if value.tzinfo is None:
            raise ValueError("created_at must be timezone-aware (UTC).")
        return value.astimezone(UTC)


def build_process_dataset_message(
    *,
    job_id: str,
    s3_bucket: str,
    s3_key: str,
) -> JobCommandMessage:
    """
    Construct a `PROCESS_DATASET` command for a job that passed validation.

    Input: the business `job_id` plus the S3 location of the validated object.
    Output: a fully populated envelope with a fresh `message_id` and a UTC
    `created_at`.

    The publisher generates `message_id` here (before the AWS call) so the same
    identifier can be logged whether the subsequent SendMessage succeeds or
    fails. Each call produces a new `message_id`, so a retried publish is
    distinguishable from the original attempt in logs.
    """
    return JobCommandMessage(
        message_id=str(uuid4()),
        message_type=MessageType.PROCESS_DATASET,
        schema_version=1,
        created_at=datetime.now(UTC),
        job_id=job_id,
        payload=ProcessDatasetPayload(s3_bucket=s3_bucket, s3_key=s3_key),
    )
